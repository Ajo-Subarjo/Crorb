def rekomendasi(rain_fall, ph, temp, hump, n, p, k, toleransi=0.10, min_cocok=5):
    nilai = [n, p, k, temp, hump, ph, rain_fall]
    hasil = []
    for tanaman, r in RULES.items():
        skor, cocok = 0.0, 0
        for i, v in enumerate(nilai):
            lo, hi = r[2 * i], r[2 * i + 1]
            rentang = hi - lo
            if rentang <= 0:
                continue
            batas = toleransi * rentang
            if lo - batas <= v <= hi + batas:
                cocok += 1
                tengah = (lo + hi) / 2
                skor += max(0.0, 1 - abs(v - tengah) / (rentang / 2))
        if cocok >= min_cocok:
            hasil.append((tanaman, round(skor / len(nilai) * 100, 1)))
    return sorted(hasil, key=lambda x: -x[1])

print(rekomendasi(rain_fall=90, ph=6.5, temp=24, hump=82, n=9, p=45, k=40))
